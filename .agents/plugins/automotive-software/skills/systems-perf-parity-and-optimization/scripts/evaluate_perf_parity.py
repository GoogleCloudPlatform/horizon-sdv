"""Evaluates C/C++ vs. Rust benchmark parity across latency, throughput, RSS, and CPU/msg metrics.

Supports three input formats in `--results-dir`:
1. `summary.json` generated by benchmark aggregators (`target_evaluation`, `early_warning_gate`,
   or `scenarios` map).
2. Raw `<prefix>_rep<N>.samples` + optional `.meta.json` and `.{client,service,daemon}_rusage.json`
   files (computing p50, p99, mean/CV, and deterministic 95% bootstrap confidence intervals).
3. Simplified `cells.json` array (`[{"scenario": ..., "metric": ..., "cpp": ..., "rust": ...}]`).

Classifies cells against `early-warning` or `parity-target` thresholds:
- `OUTPERFORM`: Rust improves on C++ by >5% (ratio <= 0.95x for lower-is-better, >= 1.05x for higher-is-better)
  with non-overlapping 95% CIs when sample CIs are available.
- `MEET TARGET`: Within target gate (p50 <= 1.10x, p99 <= 1.20x, throughput >= 0.90x, RSS <= 1.20x, CPU <= 1.10x).
- `DOCUMENTED`: Exceeds target threshold (requires root-cause and architectural note).

Exits non-zero under `--strict` if `total_cells == 0` or `pass_rate < --min-pass-rate`.
"""

from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass, field
import json
import math
from pathlib import Path
import random
import re
import statistics
import sys
import tempfile
from typing import Any, Dict, List


@dataclass
class CellEvaluation:
    scenario: str
    metric: str
    direction: str  # "lower" or "higher"
    cpp_value: float
    rust_value: float
    ratio: float
    threshold: float
    verdict: str  # "OUTPERFORM", "MEET TARGET", "DOCUMENTED"
    significance: str = "N/A"
    opt_ref: str = ""


@dataclass
class ParitySummary:
    stage: str
    source_format: str = "none"
    total_cells: int = 0
    outperform_cells: int = 0
    meet_target_cells: int = 0
    documented_cells: int = 0
    pass_rate: float = 0.0
    min_pass_rate: float = 0.85
    passed: bool = False
    cells: List[CellEvaluation] = field(default_factory=list)


STAGE_THRESHOLDS: Dict[str, Dict[str, float]] = {
    "early-warning": {
        "p50": 2.00,
        "p99": 2.50,
        "throughput": 0.50,
        "rss": 1.50,
        "cpu": 1.50,
    },
    "parity-target": {
        "p50": 1.10,
        "p99": 1.20,
        "throughput": 0.90,
        "rss": 1.20,
        "cpu": 1.10,
    },
}


def percentile(sorted_vals: List[float], pct: float) -> float:
    if not sorted_vals:
        return 0.0
    if len(sorted_vals) == 1:
        return float(sorted_vals[0])
    rank = (pct / 100.0) * (len(sorted_vals) - 1)
    low = int(math.floor(rank))
    high = int(math.ceil(rank))
    weight = rank - low
    return float(sorted_vals[low]) * (1.0 - weight) + float(sorted_vals[high]) * weight


def bootstrap_median_ci(
    rep_vals: List[float], iterations: int = 2000, seed: int = 42
) -> tuple[float, float]:
    if not rep_vals:
        return (0.0, 0.0)
    if len(rep_vals) == 1:
        return (float(rep_vals[0]), float(rep_vals[0]))
    rng = random.Random(seed)
    n = len(rep_vals)
    medians: List[float] = []
    for _ in range(iterations):
        sample = [rng.choice(rep_vals) for _ in range(n)]
        medians.append(float(statistics.median(sample)))
    medians.sort()
    return (percentile(medians, 2.5), percentile(medians, 97.5))


def bootstrap_ratio_ci(
    cpp_samples: List[float], rust_samples: List[float], iterations: int = 1000, seed: int = 42
) -> tuple[float, float]:
    if not cpp_samples or not rust_samples:
        return (1.0, 1.0)
    rng = random.Random(seed)
    n_cpp = len(cpp_samples)
    n_rust = len(rust_samples)
    ratios: List[float] = []
    for _ in range(iterations):
        c_med = sorted(cpp_samples[rng.randrange(n_cpp)] for _ in range(n_cpp))[n_cpp // 2]
        r_med = sorted(rust_samples[rng.randrange(n_rust)] for _ in range(n_rust))[n_rust // 2]
        ratios.append(r_med / c_med if c_med > 0 else 1.0)
    ratios.sort()
    return (percentile(ratios, 2.5), percentile(ratios, 97.5))


def ci_overlaps(ci_a: tuple[float, float], ci_b: tuple[float, float]) -> bool:
    return max(ci_a[0], ci_b[0]) <= min(ci_a[1], ci_b[1])


def _infer_metric_kind(metric_name: str, target_str: str = "") -> str:
    m = metric_name.lower()
    if "tput" in m or "throughput" in m or "msg/s" in m or "deliv" in m or ">=" in target_str:
        return "throughput"
    if "rss" in m or "mem" in m:
        return "rss"
    if "cpu" in m:
        return "cpu"
    if "p99" in m:
        return "p99"
    return "p50"


def evaluate_cell(
    scenario: str,
    metric: str,
    cpp_val: float,
    rust_val: float,
    stage: str = "parity-target",
    significance: str = "N/A",
    opt_ref: str = "",
) -> CellEvaluation:
    gates = STAGE_THRESHOLDS[stage]
    kind = _infer_metric_kind(metric)
    direction = "higher" if kind == "throughput" else "lower"
    ratio = (rust_val / cpp_val) if cpp_val > 0 else 1.0
    threshold = gates.get(kind, 1.10)

    if direction == "lower":
        if ratio <= 0.95 and significance != "CI OVERLAP (NOISE)":
            verdict = "OUTPERFORM"
        elif ratio <= threshold:
            verdict = "MEET TARGET"
        else:
            verdict = "DOCUMENTED"
    else:
        if ratio >= 1.05 and significance != "CI OVERLAP (NOISE)":
            verdict = "OUTPERFORM"
        elif ratio >= threshold:
            verdict = "MEET TARGET"
        else:
            verdict = "DOCUMENTED"

    return CellEvaluation(
        scenario=scenario,
        metric=metric,
        direction=direction,
        cpp_value=round(cpp_val, 3),
        rust_value=round(rust_val, 3),
        ratio=round(ratio, 3),
        threshold=threshold,
        verdict=verdict,
        significance=significance,
        opt_ref=opt_ref,
    )


def _load_summary_json_cells(data: Dict[str, Any], stage: str) -> List[CellEvaluation]:
    cells: List[CellEvaluation] = []
    target_list = data.get("target_evaluation")
    if target_list is None:
        for k, v in data.items():
            if k.endswith("_target_evaluation") and isinstance(v, list):
                target_list = v
                break
    if stage == "parity-target" and isinstance(target_list, list):
        for item in target_list:
            cpp_v = float(item.get("cpp_val") or 0.0)
            rust_v = float(item.get("rust_val") or 0.0)
            raw_status = str(item.get("status", "")).upper()
            target_str = str(item.get("target", ""))
            metric_label = str(item.get("metric", "p50"))
            kind = _infer_metric_kind(metric_label, target_str)
            direction = "higher" if kind == "throughput" else "lower"
            threshold = STAGE_THRESHOLDS[stage].get(kind, 1.10)
            ratio = (rust_v / cpp_v) if cpp_v > 0 else 1.0
            if "OUTPERFORM" in raw_status:
                verdict = "OUTPERFORM"
            elif "MEET" in raw_status:
                verdict = "MEET TARGET"
            elif raw_status:
                verdict = "DOCUMENTED"
            else:
                ev = evaluate_cell(
                    str(item.get("category", "bench")),
                    metric_label,
                    cpp_v,
                    rust_v,
                    stage=stage,
                )
                verdict = ev.verdict
            opt_ref = str(item.get("opt_ref", ""))
            if opt_ref == "—":
                opt_ref = ""
            cells.append(
                CellEvaluation(
                    scenario=str(item.get("category", "bench")),
                    metric=metric_label,
                    direction=direction,
                    cpp_value=round(cpp_v, 3),
                    rust_value=round(rust_v, 3),
                    ratio=round(ratio, 3),
                    threshold=threshold,
                    verdict=verdict,
                    significance=str(item.get("significance", "N/A")),
                    opt_ref=opt_ref,
                )
            )
        return cells

    if stage == "early-warning":
        gate_keys = ["early_warning_gate"] + [
            k for k in data if k.endswith("_early_warning_gate") and k != "early_warning_gate"
        ]
        for gate_key in gate_keys:
            gate_obj = data.get(gate_key)
            if isinstance(gate_obj, dict) and isinstance(gate_obj.get("checks"), list):
                for chk in gate_obj["checks"]:
                    cpp_v = chk.get("cpp_val", chk.get("cpp_median_p50_us", chk.get("cpp_median_msgs_per_sec")))
                    rust_v = chk.get("rust_val", chk.get("rust_median_p50_us", chk.get("rust_median_msgs_per_sec")))
                    if cpp_v is None or rust_v is None:
                        continue
                    scen = str(chk.get("transport", gate_key))
                    metric_name = str(chk.get("metric", "p50"))
                    cells.append(
                        evaluate_cell(scen, metric_name, float(cpp_v), float(rust_v), stage=stage)
                    )
                if cells:
                    return cells

    scenarios = data.get("scenarios")
    if isinstance(scenarios, dict) and scenarios:
        cells.extend(_pair_scenario_groups(scenarios, stage=stage))
    return cells


def _read_sample_file_us(path: Path) -> List[float]:
    vals: List[float] = []
    for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        try:
            vals.append(float(line) / 1000.0)
        except ValueError:
            continue
    vals.sort()
    return vals


def _analyze_raw_samples_dir(results_dir: Path, stage: str) -> List[CellEvaluation]:
    sample_files = sorted(results_dir.glob("*.samples"))
    if not sample_files:
        return []

    groups: Dict[str, List[Path]] = {}
    rep_re = re.compile(r"^(.+)_rep\d+\.samples$")
    for sf in sample_files:
        m = rep_re.match(sf.name)
        prefix = m.group(1) if m else sf.stem
        groups.setdefault(prefix, []).append(sf)

    agg: Dict[str, Dict[str, Any]] = {}
    for prefix, paths in sorted(groups.items()):
        p50s: List[float] = []
        p99s: List[float] = []
        tputs: List[float] = []
        rss_vals: List[float] = []
        cpu_vals: List[float] = []
        for sp in paths:
            s_us = _read_sample_file_us(sp)
            if s_us:
                p50s.append(percentile(s_us, 50.0))
                p99s.append(percentile(s_us, 99.0))
            meta_p = Path(str(sp) + ".meta.json")
            if meta_p.is_file():
                try:
                    meta = json.loads(meta_p.read_text(encoding="utf-8"))
                    if float(meta.get("msgs_per_sec", 0.0)) > 0:
                        tputs.append(float(meta["msgs_per_sec"]))
                except (ValueError, OSError):
                    pass
            cli_ru_p = Path(str(sp).replace(".samples", ".client_rusage.json"))
            if cli_ru_p.is_file():
                try:
                    ru = json.loads(cli_ru_p.read_text(encoding="utf-8"))
                    if float(ru.get("maxrss_kb", 0.0)) > 0:
                        rss_vals.append(float(ru["maxrss_kb"]))
                    cpu_us = float(ru.get("utime_us", 0.0)) + float(ru.get("stime_us", 0.0))
                    if cpu_us > 0:
                        cpu_vals.append(cpu_us)
                except (ValueError, OSError):
                    pass

        agg[prefix] = {
            "median_p50_us": float(statistics.median(p50s)) if p50s else 0.0,
            "p50_ci95_us": list(bootstrap_median_ci(p50s)),
            "median_p99_us": float(statistics.median(p99s)) if p99s else 0.0,
            "p99_ci95_us": list(bootstrap_median_ci(p99s)),
            "median_msgs_per_sec": float(statistics.median(tputs)) if tputs else 0.0,
            "msgs_per_sec_ci95": list(bootstrap_median_ci(tputs)),
            "median_client_maxrss_kb": float(statistics.median(rss_vals)) if rss_vals else 0.0,
            "client_maxrss_ci95_kb": list(bootstrap_median_ci(rss_vals)),
            "median_client_cpu_us": float(statistics.median(cpu_vals)) if cpu_vals else 0.0,
        }

    return _pair_scenario_groups(agg, stage=stage)


def _pair_scenario_groups(
    scenarios: Dict[str, Dict[str, Any]], stage: str
) -> List[CellEvaluation]:
    cells: List[CellEvaluation] = []
    replacements = [
        ("cpp_cpp_o3_", "rust_rust_"),
        ("cpp_cpp_", "rust_rust_"),
        ("cpp_stack_", "rust_stack_"),
        ("cpp_client_cpp_service_", "rust_client_cpp_service_"),
        ("cpp_", "rust_"),
    ]
    seen_pairs: set[tuple[str, str]] = set()
    for key in sorted(scenarios.keys()):
        for cpp_tok, rust_tok in replacements:
            if cpp_tok in key:
                rust_key = key.replace(cpp_tok, rust_tok, 1)
                if rust_key in scenarios and (key, rust_key) not in seen_pairs:
                    seen_pairs.add((key, rust_key))
                    c_obj = scenarios[key]
                    r_obj = scenarios[rust_key]
                    label = rust_key.replace(rust_tok, "")
                    metric_specs = [
                        ("p50", "median_p50_us", "p50_ci95_us"),
                        ("p99", "median_p99_us", "p99_ci95_us"),
                        ("throughput", "median_msgs_per_sec", "msgs_per_sec_ci95"),
                        ("rss", "median_client_maxrss_kb", "client_maxrss_ci95_kb"),
                    ]
                    for m_name, val_field, ci_field in metric_specs:
                        c_val = float(c_obj.get(val_field, 0.0) or 0.0)
                        r_val = float(r_obj.get(val_field, 0.0) or 0.0)
                        if c_val <= 0 or r_val <= 0:
                            continue
                        sig = "N/A"
                        c_ci = c_obj.get(ci_field)
                        r_ci = r_obj.get(ci_field)
                        if (
                            isinstance(c_ci, list)
                            and isinstance(r_ci, list)
                            and len(c_ci) == 2
                            and len(r_ci) == 2
                            and c_ci[1] > 0
                            and r_ci[1] > 0
                        ):
                            sig = (
                                "CI OVERLAP (NOISE)"
                                if ci_overlaps((float(c_ci[0]), float(c_ci[1])), (float(r_ci[0]), float(r_ci[1])))
                                else "SIGNIFICANT"
                            )
                        cells.append(
                            evaluate_cell(label, m_name, c_val, r_val, stage=stage, significance=sig)
                        )
                    break
    return cells


def evaluate_results_dir(
    results_dir: Path, stage: str = "parity-target", min_pass_rate: float = 0.85
) -> ParitySummary:
    summary = ParitySummary(stage=stage, min_pass_rate=min_pass_rate)
    summary_json = results_dir / "summary.json"
    cells_json = results_dir / "cells.json"

    if summary_json.is_file():
        data = json.loads(summary_json.read_text(encoding="utf-8"))
        summary.cells = _load_summary_json_cells(data, stage=stage)
        if summary.cells:
            summary.source_format = "summary.json"

    if not summary.cells and cells_json.is_file():
        raw_cells = json.loads(cells_json.read_text(encoding="utf-8"))
        for item in raw_cells:
            summary.cells.append(
                evaluate_cell(
                    scenario=str(item["scenario"]),
                    metric=str(item["metric"]),
                    cpp_val=float(item["cpp"]),
                    rust_val=float(item["rust"]),
                    stage=stage,
                )
            )
        if summary.cells:
            summary.source_format = "cells.json"

    if not summary.cells and results_dir.is_dir():
        summary.cells = _analyze_raw_samples_dir(results_dir, stage=stage)
        if summary.cells:
            summary.source_format = "raw_samples"

    summary.total_cells = len(summary.cells)
    for c in summary.cells:
        if c.verdict == "OUTPERFORM":
            summary.outperform_cells += 1
        elif c.verdict == "MEET TARGET":
            summary.meet_target_cells += 1
        else:
            summary.documented_cells += 1

    if summary.total_cells > 0:
        summary.pass_rate = round(
            (summary.outperform_cells + summary.meet_target_cells) / summary.total_cells, 4
        )
        summary.passed = summary.pass_rate >= min_pass_rate
    else:
        summary.pass_rate = 0.0
        summary.passed = False
    return summary


def format_markdown(summary: ParitySummary) -> str:
    status = "PASS" if summary.passed else "FAIL"
    lines = [
        f"# Performance Parity Evaluation ({status})",
        "",
        f"- **Stage**: `{summary.stage}`",
        f"- **Input Source**: `{summary.source_format}`",
        f"- **Total Evaluated Cells**: `{summary.total_cells}`",
        f"- **`OUTPERFORM`**: `{summary.outperform_cells}`",
        f"- **`MEET TARGET`**: `{summary.meet_target_cells}`",
        f"- **`DOCUMENTED`**: `{summary.documented_cells}`",
        f"- **Combined Pass Rate**: `{summary.pass_rate * 100:.2f}%` (required: `>= {summary.min_pass_rate * 100:.1f}%`)",
    ]
    if summary.total_cells == 0:
        lines.extend(
            [
                "",
                "> **ERROR**: Zero benchmark cells found in `--results-dir` (expected `summary.json`, `*.samples`, or `cells.json`).",
            ]
        )
        return "\n".join(lines)

    lines.extend(
        [
            "",
            "| Scenario | Metric | C++ Baseline | Rust Candidate | Ratio (`Rust/C++`) | Target Gate | Verdict |",
            "|---|---|---:|---:|---:|---:|---|",
        ]
    )
    for c in summary.cells[:80]:
        op = ">=" if c.direction == "higher" else "<="
        lines.append(
            f"| `{c.scenario}` | `{c.metric}` | {c.cpp_value:.2f} | {c.rust_value:.2f} | "
            f"`{c.ratio:.3f}x` | `{op} {c.threshold:.2f}x` | **{c.verdict}** |"
        )
    if len(summary.cells) > 80:
        lines.append(f"\n*(Showing first 80 of {len(summary.cells)} cells; use `--format json` for full dataset.)*")
    return "\n".join(lines)


def run_self_test() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)

        # 1. Empty directory MUST fail (0 cells != 100% pass)
        empty_dir = root / "empty"
        empty_dir.mkdir()
        empty_res = evaluate_results_dir(empty_dir, stage="parity-target", min_pass_rate=0.85)
        assert not empty_res.passed and empty_res.total_cells == 0 and empty_res.pass_rate == 0.0

        # 2. cells.json compatibility
        cells_dir = root / "cells_mode"
        cells_dir.mkdir()
        sample_cells = [
            {"scenario": "uds_rr_64", "metric": "p50", "cpp": 64.5, "rust": 67.8},
            {"scenario": "uds_rr_65536", "metric": "p50", "cpp": 203.0, "rust": 160.3},
            {"scenario": "udp_rr_1400", "metric": "p50", "cpp": 18935.0, "rust": 133.4},
            {"scenario": "uds_stream_64", "metric": "throughput", "cpp": 115.6, "rust": 241.0},
            {"scenario": "fanout_50", "metric": "throughput", "cpp": 388.0, "rust": 730.0},
            {"scenario": "daemon_rss", "metric": "rss", "cpp": 11920.0, "rust": 9380.0},
        ]
        (cells_dir / "cells.json").write_text(json.dumps(sample_cells), encoding="utf-8")
        res = evaluate_results_dir(cells_dir, stage="parity-target", min_pass_rate=0.85)
        assert res.passed and res.source_format == "cells.json"
        assert res.outperform_cells == 5 and res.meet_target_cells == 1

        # 3. summary.json (`target_evaluation` schema)
        sum_dir = root / "summary_mode"
        sum_dir.mkdir()
        (sum_dir / "summary.json").write_text(
            json.dumps(
                {
                    "target_evaluation": [
                        {
                            "category": "S1 Local UDS RR",
                            "metric": "UDS RR 64 B p50",
                            "cpp_val": 32.8,
                            "rust_val": 29.6,
                            "target": "<= +10%",
                            "status": "OUTPERFORMS C++",
                            "significance": "SIGNIFICANT",
                        },
                        {
                            "category": "S7 Multi-App",
                            "metric": "10-Svc 100-App Echo p50",
                            "cpp_val": 36.63,
                            "rust_val": 35.23,
                            "target": "<= +10%",
                            "status": "MEETS TARGET",
                            "significance": "CI OVERLAP (NOISE)",
                        },
                    ]
                }
            ),
            encoding="utf-8",
        )
        sum_res = evaluate_results_dir(sum_dir, stage="parity-target", min_pass_rate=0.85)
        assert sum_res.passed and sum_res.source_format == "summary.json"
        assert sum_res.total_cells == 2 and sum_res.outperform_cells == 1 and sum_res.meet_target_cells == 1

        # 4. Raw *.samples + *.meta.json + *.client_rusage.json mode
        raw_dir = root / "raw_mode"
        raw_dir.mkdir()
        for rep in (1, 2, 3):
            (raw_dir / f"s1_cpp_cpp_uds_rr_64_rep{rep}.samples").write_text(
                "\n".join(str(33000 + rep * 100 + i * 10) for i in range(20)) + "\n",
                encoding="utf-8",
            )
            (raw_dir / f"s1_cpp_cpp_uds_rr_64_rep{rep}.samples.meta.json").write_text(
                json.dumps({"msgs_per_sec": 29000.0}), encoding="utf-8"
            )
            (raw_dir / f"s1_cpp_cpp_uds_rr_64_rep{rep}.client_rusage.json").write_text(
                json.dumps({"maxrss_kb": 6400, "utime_us": 40000, "stime_us": 30000}), encoding="utf-8"
            )
            (raw_dir / f"s1_rust_rust_uds_rr_64_rep{rep}.samples").write_text(
                "\n".join(str(29500 + rep * 100 + i * 10) for i in range(20)) + "\n",
                encoding="utf-8",
            )
            (raw_dir / f"s1_rust_rust_uds_rr_64_rep{rep}.samples.meta.json").write_text(
                json.dumps({"msgs_per_sec": 32500.0}), encoding="utf-8"
            )
            (raw_dir / f"s1_rust_rust_uds_rr_64_rep{rep}.client_rusage.json").write_text(
                json.dumps({"maxrss_kb": 3400, "utime_us": 30000, "stime_us": 25000}), encoding="utf-8"
            )
        raw_res = evaluate_results_dir(raw_dir, stage="parity-target", min_pass_rate=0.85)
        assert raw_res.passed and raw_res.source_format == "raw_samples" and raw_res.total_cells == 4

        ci_low, ci_high = bootstrap_ratio_ci([100.0, 102.0, 98.0], [50.0, 51.0, 49.0], iterations=200)
        assert 0.45 <= ci_low <= ci_high <= 0.55

    print(
        "SELF-TEST PASS: evaluate_perf_parity.py verified empty-dir fail, summary.json, raw .samples, cells.json, and bootstrap CI."
    )
    return 0


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", default=".")
    parser.add_argument(
        "--stage", choices=["early-warning", "parity-target"], default="parity-target"
    )
    parser.add_argument("--min-pass-rate", type=float, default=0.85)
    parser.add_argument("--format", choices=["markdown", "json", "text"], default="markdown")
    parser.add_argument("--strict", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)

    if args.self_test:
        return run_self_test()

    summary = evaluate_results_dir(Path(args.results_dir), args.stage, args.min_pass_rate)
    if args.format == "json":
        print(json.dumps(asdict(summary), indent=2))
    else:
        print(format_markdown(summary))

    if args.strict and not summary.passed:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
