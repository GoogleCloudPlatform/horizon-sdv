# Regenerates deepcopy code and the module CRDs from api/v1alpha1.
# Needs controller-gen v0.20.0 on PATH (go install sigs.k8s.io/controller-tools/cmd/controller-gen@v0.20.0).

set -euo pipefail

APP_DIR="$(cd "$(dirname "$0")/.." && pwd)"
REPO_ROOT="$(cd "${APP_DIR}/../../../../../.." && pwd)"
CRD_DIR="${REPO_ROOT}/gitops/modules/storage-mirror-module/crds"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

cd "${APP_DIR}"
controller-gen object:headerFile=hack/boilerplate.go.txt paths=./api/...
controller-gen crd paths=./api/... output:crd:dir="${TMP}"

for kind in storagemirrorconfigs storagemirrors; do
  {
    sed -e 's#^// #\# #' -e 's#^//$#\##' hack/boilerplate.go.txt
    echo "#"
    echo "# Generated by hack/update-crds.sh from"
    echo "# terraform/modules/sdv-container-images/images/storage-mirror-module/storage-mirror-module-app/api/v1alpha1."
    echo "# Delete=false and Prune=false keep the CRD (and every StorageMirror with its data finalizer) when the module is disabled."
    sed -e '/^---$/d' \
        -e 's#^    controller-gen.kubebuilder.io/version: \(.*\)$#    controller-gen.kubebuilder.io/version: \1\n    argocd.argoproj.io/sync-options: Delete=false,Prune=false#' \
        "${TMP}/storagemirror.horizon-sdv.io_${kind}.yaml"
  } > "${CRD_DIR}/${kind}.yaml"
done
echo "CRDs written to ${CRD_DIR}"
