// Package secrets creates and reuses the REST API token and TLS Secrets. The controller owns them (not Argo CD), so
// they are generated once, never regenerated by a render, and survive a module disable like the mirror data.
package secrets

import (
	"bytes"
	"context"
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/json"
	"encoding/pem"
	"fmt"
	"math/big"
	"time"

	corev1 "k8s.io/api/core/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"sigs.k8s.io/controller-runtime/pkg/client"

	smv1 "storage-mirror-module/api/v1alpha1"
)

const (
	KeyTokens = "tokens.json"
	KeyCA     = "ca.crt"

	CallerDefault    = "default"
	CallerHorizonAPI = "horizon-api"
	CallerAgent      = "storage-mirror-agent"

	certValidity = 8250 * 24 * time.Hour
)

// Callers get one token each; tokens.json may also carry a "previous" token per caller for rotation.
var Callers = []string{CallerDefault, CallerHorizonAPI, CallerAgent}

// Config names the Secrets and the namespaces that receive copies.
type Config struct {
	Namespace           string
	WorkflowNamespace   string
	HorizonAPINamespace string
	TokenSecret         string
	TLSSecret           string
	// ServiceName is the controller Service; the certificate covers its in-cluster DNS names.
	ServiceName string
}

// Material is what the API server needs.
type Material struct {
	TokensJSON string
	CertPEM    []byte
	KeyPEM     []byte
	CAPEM      []byte
}

type tokenEntry struct {
	Current  string `json:"current"`
	Previous string `json:"previous,omitempty"`
}

// Ensure creates missing Secrets, keeps the copies in the workflows and Horizon API namespaces in step with the
// controller namespace, and returns the token map and the server certificate. Existing values are never replaced.
func Ensure(ctx context.Context, c client.Client, cfg Config) (*Material, error) {
	tokens, err := ensureTokens(ctx, c, cfg)
	if err != nil {
		return nil, err
	}
	m, err := ensureTLS(ctx, c, cfg)
	if err != nil {
		return nil, err
	}
	tj, _ := json.Marshal(tokens)
	m.TokensJSON = string(tj)
	copies := []struct {
		ns, name string
		data     map[string][]byte
	}{
		{cfg.WorkflowNamespace, cfg.TokenSecret, map[string][]byte{CallerAgent: []byte(tokens[CallerAgent].Current)}},
		{cfg.HorizonAPINamespace, cfg.TokenSecret, map[string][]byte{CallerHorizonAPI: []byte(tokens[CallerHorizonAPI].Current)}},
		{cfg.WorkflowNamespace, cfg.TLSSecret, map[string][]byte{KeyCA: m.CAPEM}},
		{cfg.HorizonAPINamespace, cfg.TLSSecret, map[string][]byte{KeyCA: m.CAPEM}},
	}
	for _, cp := range copies {
		if err := apply(ctx, c, cp.ns, cp.name, corev1.SecretTypeOpaque, cp.data); err != nil {
			return nil, err
		}
	}
	return m, nil
}

func ensureTokens(ctx context.Context, c client.Client, cfg Config) (map[string]tokenEntry, error) {
	tokens := map[string]tokenEntry{}
	var s corev1.Secret
	err := c.Get(ctx, client.ObjectKey{Namespace: cfg.Namespace, Name: cfg.TokenSecret}, &s)
	switch {
	case apierrors.IsNotFound(err):
	case err != nil:
		return nil, err
	default:
		if raw := s.Data[KeyTokens]; len(raw) > 0 {
			if err := json.Unmarshal(raw, &tokens); err != nil {
				return nil, fmt.Errorf("secret %s/%s %s: %w", cfg.Namespace, cfg.TokenSecret, KeyTokens, err)
			}
		}
	}
	for _, caller := range Callers {
		if tokens[caller].Current == "" {
			t := tokens[caller]
			t.Current = randomToken()
			tokens[caller] = t
		}
	}
	tj, _ := json.Marshal(tokens)
	data := map[string][]byte{KeyTokens: tj}
	for _, caller := range Callers {
		data[caller] = []byte(tokens[caller].Current)
	}
	if err := apply(ctx, c, cfg.Namespace, cfg.TokenSecret, corev1.SecretTypeOpaque, data); err != nil {
		return nil, err
	}
	return tokens, nil
}

func ensureTLS(ctx context.Context, c client.Client, cfg Config) (*Material, error) {
	var s corev1.Secret
	err := c.Get(ctx, client.ObjectKey{Namespace: cfg.Namespace, Name: cfg.TLSSecret}, &s)
	if err == nil && len(s.Data[corev1.TLSCertKey]) > 0 && len(s.Data[corev1.TLSPrivateKeyKey]) > 0 && len(s.Data[KeyCA]) > 0 {
		return &Material{CertPEM: s.Data[corev1.TLSCertKey], KeyPEM: s.Data[corev1.TLSPrivateKeyKey], CAPEM: s.Data[KeyCA]}, nil
	}
	if err != nil && !apierrors.IsNotFound(err) {
		return nil, err
	}
	m, err := generate(cfg)
	if err != nil {
		return nil, err
	}
	data := map[string][]byte{corev1.TLSCertKey: m.CertPEM, corev1.TLSPrivateKeyKey: m.KeyPEM, KeyCA: m.CAPEM}
	if err := apply(ctx, c, cfg.Namespace, cfg.TLSSecret, corev1.SecretTypeTLS, data); err != nil {
		return nil, err
	}
	return m, nil
}

// DNSNames are the names the server certificate covers.
func DNSNames(cfg Config) []string {
	svc := cfg.ServiceName
	return []string{
		fmt.Sprintf("%s.%s.svc.cluster.local", svc, cfg.Namespace),
		svc,
		fmt.Sprintf("%s.%s", svc, cfg.Namespace),
		fmt.Sprintf("%s.%s.svc", svc, cfg.Namespace),
	}
}

func generate(cfg Config) (*Material, error) {
	now := time.Now()
	caKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, err
	}
	caTmpl := &x509.Certificate{
		SerialNumber:          serial(),
		Subject:               pkix.Name{CommonName: cfg.ServiceName + "-ca"},
		NotBefore:             now.Add(-time.Hour),
		NotAfter:              now.Add(certValidity),
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageDigitalSignature,
		BasicConstraintsValid: true,
		IsCA:                  true,
	}
	caDER, err := x509.CreateCertificate(rand.Reader, caTmpl, caTmpl, &caKey.PublicKey, caKey)
	if err != nil {
		return nil, err
	}
	ca, _ := x509.ParseCertificate(caDER)
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, err
	}
	names := DNSNames(cfg)
	tmpl := &x509.Certificate{
		SerialNumber: serial(),
		Subject:      pkix.Name{CommonName: names[0]},
		DNSNames:     names,
		NotBefore:    now.Add(-time.Hour),
		NotAfter:     now.Add(certValidity),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, ca, &key.PublicKey, caKey)
	if err != nil {
		return nil, err
	}
	keyDER, err := x509.MarshalECPrivateKey(key)
	if err != nil {
		return nil, err
	}
	return &Material{
		CertPEM: pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}),
		KeyPEM:  pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: keyDER}),
		CAPEM:   pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: caDER}),
	}, nil
}

// apply creates the Secret, or updates its data when it differs.
func apply(ctx context.Context, c client.Client, ns, name string, typ corev1.SecretType, data map[string][]byte) error {
	var cur corev1.Secret
	err := c.Get(ctx, client.ObjectKey{Namespace: ns, Name: name}, &cur)
	if apierrors.IsNotFound(err) {
		s := &corev1.Secret{
			ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: ns, Labels: map[string]string{
				"app.kubernetes.io/name": "storage-mirror-module",
				smv1.LabelModule:         smv1.ModuleName,
			}},
			Type: typ,
			Data: data,
		}
		if err := c.Create(ctx, s); err != nil {
			return fmt.Errorf("create secret %s/%s: %w", ns, name, err)
		}
		return nil
	}
	if err != nil {
		return err
	}
	if sameData(cur.Data, data) {
		return nil
	}
	if cur.Data == nil {
		cur.Data = map[string][]byte{}
	}
	for k, v := range data {
		cur.Data[k] = v
	}
	if err := c.Update(ctx, &cur); err != nil {
		return fmt.Errorf("update secret %s/%s: %w", ns, name, err)
	}
	return nil
}

func sameData(have, want map[string][]byte) bool {
	for k, v := range want {
		if !bytes.Equal(have[k], v) {
			return false
		}
	}
	return true
}

const tokenAlphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"

func randomToken() string {
	b := make([]byte, 48)
	max := big.NewInt(int64(len(tokenAlphabet)))
	for i := range b {
		n, err := rand.Int(rand.Reader, max)
		if err != nil {
			panic(err)
		}
		b[i] = tokenAlphabet[n.Int64()]
	}
	return string(b)
}

func serial() *big.Int {
	n, _ := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 127))
	return n
}
